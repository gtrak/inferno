//! Build for the inferno Zig core.
//!
//! Two products come out of this file: the static library `libinferno_core.a`
//! that the Rust server links, and the CUDA cubins it embeds. `nvcc` is driven
//! from here so that `zig build` is the single entry point for the whole hot
//! path; the cubins are compiled into the archive so the engine never reads
//! kernel files from disk at run time.

const std = @import("std");

const assert = std.debug.assert;

/// CUDA toolkit used when the environment does not name one.
const cuda_home_default = "/usr/local/cuda-13.2";

/// Environment variable that overrides `cuda_home_default`.
const cuda_home_variable = "CUDA_HOME";

/// Path of `nvcc` inside a CUDA toolkit.
const nvcc_relative_path = "bin/nvcc";

/// GPU architecture: Blackwell consumer parts need `sm_120a` for the
/// block-scaled tensor core instructions.
const cuda_arch = "sm_120a";

/// Only files with this suffix are compiled as kernels.
const kernel_extension = ".cu";

const kernels_directory = "src/kernels";

/// Model-level glue is a `.cu` file too, and it lives beside the Zig that drives
/// it rather than in `src/kernels`. The cubin pass therefore walks every
/// directory here; a kernel in none of them is silently absent from the table.
const kernel_directories = [_][]const u8{ "src/kernels", "src/model" };
const cubin_table_file_name = "generated_cubins.zig";

/// Hardware-probe binary: `zig build probe` installs it here.
const probe_binary_name = "inferno-probe";
const probe_root_source_file = "src/bench/main.zig";

/// The hardware layer as a named module: `src/bench/` imports it as `hw`, so
/// the CLI never reaches outside its own directory to find the driver layer.
const hw_module_name = "hw";
const hw_root_source_file = "src/hw/bench.zig";

/// The fp32 CPU reference (issue I-005): the oracle every kernel is checked
/// against. It has its own test root so `zig build refcheck` runs the golden
/// comparison suite without linking the CUDA driver.
const ref_root_file = "src/ref/mod.zig";
const ref_tests_file = "src/ref/tests.zig";
const ref_library_name = "inferno_ref";

/// Golden fixtures the reference tests read, relative to the repo root.
const fixtures_directory = "tests/golden/tiny";

/// Root of the core module, and of the test binary `zig build test` runs.
const core_root_file = "src/c_api.zig";

/// Root of the `attntest` step (issue I-008): the indexed-attention harness
/// on its own, so iterating on those kernels need not build the C ABI surface.
const attn_tests_file = "src/attn_tests.zig";

/// Header of the generated cubin table, up to the per-kernel entries.
const cubin_table_header =
    \\//! Generated by core/build.zig from core/src/kernels/*.cu.
    \\//!
    \\//! Do not edit and do not commit: the file lives in the build cache.
    \\
    \\/// One CUDA binary embedded in the static library.
    \\pub const Cubin = extern struct {
    \\    name: [*:0]const u8,
    \\    bytes: [*]const u8,
    \\    length: u64,
    \\};
    \\
    \\pub const cubins = [_]Cubin{
    \\
;

/// Golden fixtures embedded into the unit tests, so neither the tests nor the
/// gate need the real checkpoint on disk.
const golden_fixtures = [_]struct { []const u8, []const u8 }{
    .{ "golden_quant_nvfp4", "../tests/golden/quant/nvfp4_case.safetensors" },
    .{ "golden_quant_fp8_blockwise", "../tests/golden/quant/fp8_blockwise_case.safetensors" },
};

/// Entry point of `zig build manifest`.
const manifest_main_path = "src/weights/manifest_main.zig";

/// Name of the report the manifest step installs into `zig-out`.
const manifest_file_name = "manifest.json";

/// Checkpoint used when neither `-Dmodel-dir` nor `INFERNO_MODEL_DIR` is set.
const model_directory_default = "/home/gary/models/qwen38-flash-next-nvfp4";

/// Environment variable that overrides `model_directory_default`.
const model_directory_variable = "INFERNO_MODEL_DIR";

/// The cubin generation pass: compiles every kernel and embeds the result.
const CubinTable = struct {
    write_files: *std.Build.Step.WriteFile,
    nvcc_path: []const u8,
    source: std.ArrayList(u8),
    kernel_count: u32,

    fn init(b: *std.Build, nvcc_path: []const u8) !CubinTable {
        assert(nvcc_path.len > 0);
        assert(cubin_table_file_name.len > 0);

        var table: CubinTable = .{
            .write_files = b.addWriteFiles(),
            .nvcc_path = nvcc_path,
            .source = std.ArrayList(u8).init(b.allocator),
            .kernel_count = 0,
        };
        try table.source.appendSlice(cubin_table_header);
        assert(table.source.items.len == cubin_table_header.len);
        return table;
    }

    /// Compiles one `.cu` file and appends its entry to the table.
    fn add_kernel(
        table: *CubinTable,
        b: *std.Build,
        directory: []const u8,
        file_name: []const u8,
    ) !void {
        assert(std.mem.endsWith(u8, file_name, kernel_extension));
        assert(table.nvcc_path.len > 0);
        assert(directory.len > 0);

        const suffix_length = kernel_extension.len;
        const kernel_name = file_name[0 .. file_name.len - suffix_length];
        const source_path = b.fmt("{s}/{s}", .{ directory, file_name });

        const nvcc = b.addSystemCommand(&.{table.nvcc_path});
        nvcc.addArg(b.fmt("-arch={s}", .{cuda_arch}));
        nvcc.addArgs(&.{ "--cubin", "-O3", "-lineinfo" });
        nvcc.addFileArg(b.path(source_path));
        nvcc.addArg("-o");
        const cubin = nvcc.addOutputFileArg(kernel_name);
        _ = table.write_files.addCopyFile(cubin, kernel_name);

        const length_before = table.source.items.len;
        try table.source.appendSlice(b.fmt(
            "    .{{ .name = \"{s}\", .bytes = @embedFile(\"{s}\")," ++
                " .length = @embedFile(\"{s}\").len }},\n",
            .{ kernel_name, kernel_name, kernel_name },
        ));
        table.kernel_count += 1;
        assert(table.source.items.len > length_before);
    }

    /// Closes the table and returns the directory holding the generated file.
    fn finish(table: *CubinTable) !std.Build.LazyPath {
        assert(table.kernel_count > 0);
        assert(table.source.items.len > cubin_table_header.len);

        try table.source.appendSlice("};\n");
        _ = table.write_files.add(cubin_table_file_name, table.source.items);
        return table.write_files.getDirectory();
    }
};

pub fn build(b: *std.Build) !void {
    assert(cuda_arch.len > 0);
    assert(kernel_extension.len > 0);

    const target = b.standardTargetOptions(.{});
    const optimize = b.option(
        std.builtin.OptimizeMode,
        "optimize",
        "Prioritize performance, safety, or binary size",
    ) orelse .ReleaseSafe;

    const cubin_directory = try build_kernels(b);

    const library = b.addLibrary(.{
        .name = "inferno_core",
        .linkage = .static,
        .root_module = create_core_module(
            b,
            target,
            optimize,
            cubin_directory,
            core_root_file,
        ),
    });
    // The Rust server links this archive into its own position independent
    // executable, so every object in the archive must be position independent.
    library.root_module.pic = true;
    // Zig's own runtime helpers (`__zig_probe_stack` and friends) are not
    // supplied by rustc, so they travel inside the archive.
    library.bundle_compiler_rt = true;
    b.installArtifact(library);

    const core_tests = b.addTest(.{
        .root_module = create_core_module(
            b,
            target,
            optimize,
            cubin_directory,
            core_root_file,
        ),
    });
    const run_core_tests = b.addRunArtifact(core_tests);

    // The issue's gate is `zig build attntest`: the indexed-attention harness
    // is a named step of its own so it can be run (and debugged) alone.
    const attn_tests = b.addTest(.{
        .root_module = create_core_module(
            b,
            target,
            optimize,
            cubin_directory,
            attn_tests_file,
        ),
    });
    const run_attn_tests = b.addRunArtifact(attn_tests);
    const attntest = b.step(
        "attntest",
        "Run the indexed-attention harness (I-008)",
    );
    attntest.dependOn(&run_attn_tests.step);

    // The probe is installed by the default step as well, because the gate runs
    // `tools/gate.sh` and then executes the binary it just built.
    const hw_module = create_hw_module(b, target, optimize);
    const probe_module = create_probe_module(
        b,
        target,
        optimize,
        hw_module,
        cubin_directory,
    );
    const probe = b.addExecutable(.{
        .name = probe_binary_name,
        .root_module = probe_module,
    });
    const install_probe = b.addInstallArtifact(probe, .{});
    b.getInstallStep().dependOn(&install_probe.step);
    b.step(
        "probe",
        "Build the hardware probe (zig-out/bin/" ++ probe_binary_name ++ ")",
    ).dependOn(&install_probe.step);

    const probe_tests = b.addTest(.{ .root_module = probe_module });
    const run_probe_tests = b.addRunArtifact(probe_tests);

    const test_step = b.step("test", "Run unit tests");
    // Both binaries bring up a CUDA context on device 0. With no edge between them Zig
    // runs them concurrently, and a reviewer measured 2 of 5 `zig build test` runs failing
    // at different GPU tests as a result. Serialise: probe waits for core.
    run_probe_tests.step.dependOn(&run_core_tests.step);
    test_step.dependOn(&run_core_tests.step);
    test_step.dependOn(&run_probe_tests.step);

    build_manifest(b, target, optimize);

    // The CPU reference is built by default so it cannot rot, and its golden
    // comparison suite is a separate step (it reads the committed fixtures).
    const ref_library = b.addLibrary(.{
        .name = ref_library_name,
        .linkage = .static,
        .root_module = create_ref_module(b, target, optimize, ref_root_file),
    });
    ref_library.root_module.pic = true;
    ref_library.bundle_compiler_rt = true;
    b.installArtifact(ref_library);

    const ref_tests = b.addTest(.{
        .root_module = create_ref_module(b, target, optimize, ref_tests_file),
    });
    const run_ref_tests = b.addRunArtifact(ref_tests);
    run_ref_tests.setCwd(b.path(".."));
    const refcheck = b.step(
        "refcheck",
        "Compare the CPU reference against the HF golden traces",
    );
    refcheck.dependOn(&run_ref_tests.step);
}

/// Creates the hardware layer module that `src/bench/` imports as `hw`.
fn create_hw_module(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    assert(hw_root_source_file.len > 0);
    assert(hw_module_name.len > 0);

    return b.createModule(.{
        .root_source_file = b.path(hw_root_source_file),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
}

/// Creates the module behind `zig-out/bin/inferno-probe`.
fn create_probe_module(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    hw_module: *std.Build.Module,
    cubin_directory: std.Build.LazyPath,
) *std.Build.Module {
    assert(probe_root_source_file.len > 0);
    assert(hw_module_name.len > 0);
    assert(cubin_table_file_name.len > 0);

    const module = b.createModule(.{
        .root_source_file = b.path(probe_root_source_file),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    module.addImport(hw_module_name, hw_module);
    // The probe measures achieved GEMM throughput, which means it has to load and
    // launch the embedded kernels; without this it cannot see any cubin.
    module.addAnonymousImport("generated_cubins", .{
        .root_source_file = cubin_directory.path(b, cubin_table_file_name),
    });
    return module;
}

/// Adds the `manifest` step: types the checkpoint and writes `zig-out/manifest.json`.
///
/// The tool is not part of the library, but it shares the weight code under
/// `src/weights`, which is why it is built from the same source tree.
///
/// The step is opt-in: the install step (what a bare `zig build` requests) must
/// not depend on it, because the 132 GB checkpoint lives outside the tree and
/// is absent on most machines. `zig build` therefore stays checkpoint free and
/// only `zig build manifest` reads the model files.
fn build_manifest(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) void {
    assert(manifest_main_path.len > 0);
    assert(manifest_file_name.len > 0);

    const module = b.createModule(.{
        .root_source_file = b.path(manifest_main_path),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    const tool = b.addExecutable(.{ .name = "inferno-manifest", .root_module = module });

    const run = b.addRunArtifact(tool);
    // The checkpoint is not a build input (it lives outside the tree and is
    // 132 GB), so the step must not be treated as up to date when nothing in
    // the build graph changed: every `zig build manifest` re-reads the headers.
    run.has_side_effects = true;
    run.addArg(model_directory(b));
    const report = run.addOutputFileArg(manifest_file_name);
    const install = b.addInstallFileWithDir(report, .prefix, manifest_file_name);
    const step = b.step("manifest", "Write zig-out/manifest.json from the checkpoint");
    step.dependOn(&install.step);
}

/// Checkpoint directory: `-Dmodel-dir`, then `INFERNO_MODEL_DIR`, then the default.
fn model_directory(b: *std.Build) []const u8 {
    assert(model_directory_default.len > 0);
    assert(model_directory_variable.len > 0);

    const override = b.option([]const u8, "model-dir", "Checkpoint directory");
    if (override) |given| {
        return given;
    } else {
        // Fall through to the environment, then to the fixed path.
    }
    const from_environment = std.process.getEnvVarOwned(
        b.allocator,
        model_directory_variable,
    );
    if (from_environment) |value| {
        return value;
    } else |_| {
        return model_directory_default;
    }
}

/// Creates the CPU reference module rooted at `root_file`.
fn create_ref_module(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    root_file: []const u8,
) *std.Build.Module {
    assert(ref_root_file.len > 0);
    assert(fixtures_directory.len > 0);

    const fixtures = b.addOptions();
    fixtures.addOption(
        []const u8,
        "path",
        b.pathFromRoot("../" ++ fixtures_directory),
    );

    const module = b.createModule(.{
        .root_source_file = b.path(root_file),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .pic = true,
    });
    module.addOptions("fixtures_dir", fixtures);
    return module;
}

/// Creates the module compiled into the library, the unit tests and
/// `attntest`, rooted at `root_file`.
fn create_core_module(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    cubin_directory: std.Build.LazyPath,
    root_file: []const u8,
) *std.Build.Module {
    assert(cubin_table_file_name.len > 0);
    assert(kernels_directory.len > 0);
    assert(root_file.len > 0);

    const module = b.createModule(.{
        .root_source_file = b.path(root_file),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .pic = true,
    });
    module.addAnonymousImport("generated_cubins", .{
        .root_source_file = cubin_directory.path(b, cubin_table_file_name),
    });
    for (golden_fixtures) |fixture| {
        module.addAnonymousImport(fixture[0], .{
            .root_source_file = b.path(fixture[1]),
        });
    }

    // The kernel lanes gate against the CPU reference in `src/ref/`, and that
    // reference reads the committed golden fixtures through an anonymous
    // `fixtures_dir` option. The reference module declares the same option for
    // `refcheck`; the core module needs it too, otherwise importing `ref/` from
    // a kernel test fails with "no module named 'fixtures_dir'". The path is
    // absolute, so tests never depend on the working directory.
    const fixtures_path = b.addOptions();
    fixtures_path.addOption(
        []const u8,
        "path",
        b.pathFromRoot("../" ++ fixtures_directory),
    );
    module.addOptions("fixtures_dir", fixtures_path);
    return module;
}

/// Compiles every kernel into a cubin and returns the table's directory.
fn build_kernels(b: *std.Build) !std.Build.LazyPath {
    assert(kernels_directory.len > 0);
    assert(kernel_extension.len > 0);

    var table = try CubinTable.init(b, try find_nvcc(b));
    for (kernel_directories) |directory| {
        try add_kernels_in_directory(&table, b, directory);
    }

    if (table.kernel_count == 0) {
        std.debug.print(
            "error: no {s} files in any of {d} kernel directories;" ++
                " the cubin table would be empty\n",
            .{ kernel_extension, kernel_directories.len },
        );
        return error.NoKernelsFound;
    } else {
        assert(table.kernel_count > 0);
    }
    return table.finish();
}

/// Appends every `.cu` file in `directory` to the table. A missing directory is
/// a hard error rather than an empty pass: a typo would otherwise drop a kernel
/// from the table and surface as a runtime "cubin missing" on the GPU.
fn add_kernels_in_directory(
    table: *CubinTable,
    b: *std.Build,
    directory: []const u8,
) !void {
    assert(directory.len > 0);
    assert(kernels_directory.len > 0);

    var kernels = b.build_root.handle.openDir(directory, .{
        .iterate = true,
    }) catch |err| {
        std.debug.print(
            "error: cannot open kernel directory {s}: {s}\n",
            .{ directory, @errorName(err) },
        );
        return err;
    };
    defer kernels.close();

    const count_before = table.kernel_count;
    var iterator = kernels.iterate();
    while (try iterator.next()) |entry| {
        const is_kernel = entry.kind == .file and
            std.mem.endsWith(u8, entry.name, kernel_extension);
        if (is_kernel) {
            try table.add_kernel(b, directory, entry.name);
        } else {
            // Sub-directories and non-CUDA files hold no kernels.
        }
    }
    assert(table.kernel_count >= count_before);
}

/// Resolves the `nvcc` binary, preferring `CUDA_HOME` over the default toolkit.
fn find_nvcc(b: *std.Build) ![]const u8 {
    assert(nvcc_relative_path.len > 0);
    assert(cuda_home_default.len > 0);

    const nvcc_path = b.fmt("{s}/{s}", .{ cuda_home(), nvcc_relative_path });
    if (std.fs.accessAbsolute(nvcc_path, .{})) {
        assert(nvcc_path.len > nvcc_relative_path.len);
        return nvcc_path;
    } else |_| {
        std.debug.print("error: no nvcc at {s}\n", .{nvcc_path});
        std.debug.print("set {s} to a CUDA toolkit\n", .{cuda_home_variable});
        return error.NvccNotFound;
    }
}

/// CUDA toolkit directory: `CUDA_HOME` when set, the default install otherwise.
fn cuda_home() []const u8 {
    assert(cuda_home_default.len > 0);
    assert(cuda_home_variable.len > 0);

    if (std.posix.getenv(cuda_home_variable)) |override| {
        return override;
    } else {
        return cuda_home_default;
    }
}
