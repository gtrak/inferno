def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("mode", choices=("inspect", "verify", "kl", "router", "router-trace", "to-trace"))
    parser.add_argument("--case", default="wiki2_r0", help="logits case id (kl, to-trace)")
    parser.add_argument("--candidate", default="candidate-xestrata", help="logits candidate directory")
    parser.add_argument("--start", type=int, default=None, help="first scored row (default: 55 for wiki2_*, else 0)")
    parser.add_argument("--block-rows", type=int, default=128, help="rows per float64 block")
    parser.add_argument("--model", default="~/models/qwen38-flash-next-nvfp4", help="local checkpoint (router)")
    parser.add_argument("--layers", type=int, default=48, help="gate matrices to compare (router)")
    parser.add_argument("--rows", type=int, default=64, help="rows of the compact arrays to fetch (router-trace)")
    parser.add_argument("--out", default=None, help="output .safetensors (to-trace)")
    return parser


def main(argv: list[str]) -> int:
    arguments = build_parser().parse_args(argv)
    if arguments.mode == "inspect":
        return cmd_inspect(arguments)
    if arguments.mode == "verify":
        return cmd_verify(arguments)
    if arguments.mode == "kl":
        return cmd_kl(arguments)
    if arguments.mode == "router":
        return cmd_router(arguments)
    if arguments.mode == "router-trace":
        return cmd_router_trace(arguments)
    if not arguments.out:
        raise AssertionError("to-trace needs --out")
    return cmd_to_trace(arguments)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
