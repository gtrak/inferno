def inspect_vemloir() -> dict:
    """The calibration packs: only ids and lengths. This is the answer to the per-layer question."""
    import safetensors.torch

    parts = {}
    for part in ("agents", "chat", "multimodal"):
        path = fetch("vemloir", f"{part}/cal_trace.safetensors", 512 << 20)
        tensors = safetensors.torch.load_file(str(path))
        parts[part] = {
            "file_bytes": path.stat().st_size,
            "tensors": {name: {"dtype": str(t.dtype), "shape": list(t.shape)} for name, t in sorted(tensors.items())},
            "rows": int(tensors["lengths"].numel()),
            "tokens_min": int(tensors["lengths"].min()),
            "tokens_max": int(tensors["lengths"].max()),
            "tokens_total": int(tensors["lengths"].sum()),
            "image_tensors": sum(1 for name in tensors if name.startswith("mm_image_")),
        }
    return {
        "provides": "prompt token ids (right-padded with 0) and true lengths, plus raw image bytes for the multimodal part",
        "does_not_provide": (
            "no logits, no hidden states, no per-layer activations: it is a calibration input set, so it can "
            "supply realistic long prompts but cannot grade any output"
        ),
        "parts": parts,
        "provenance": {
            "generator": "Qwen3.8-Flash-Next itself, served as nvidia/Qwen3.8-Flash-Next-FP4-Local in vLLM (card)",
            "model_revision": "not stated",
            "tokeniser": "the checkpoint's chat template; no tokeniser file or hash is published beside the ids",
            "corpus": "40 agent sessions / 700 chat rows / 105 image rows, self-generated; ids are authoritative in the files",
            "dtype": "ids are int64; no model state",
        },
    }


