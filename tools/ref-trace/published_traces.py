"""Provenance-verified ingestion of published Qwen3.8-Flash-Next traces (issue I-031, part 2).

Part 1 built the generator, proved it on the tiny fixture, and recorded that `transformers` at the
pinned commit cannot load the 124 GB NVFP4 checkpoint (REAL_REFERENCE.md §5.3). Part 2 asked the
next question — can a reference be *run* here at all — and answered it in two steps:

1. **Software is not the wall.** vLLM 0.34.0 registers `Qwen4ExpForCausalLM`,
   `Qwen4ExpForConditionalGeneration` and `Qwen4ExpMTP`, and understands the checkpoint's
   `modelopt` quantisation. `transformers` 5.24 refuses the quantiser, but vLLM does not.
2. **Capacity is the wall.** The checkpoint is 123.6 GiB of weights against 63.7 GiB of VRAM and
   ~55 GiB of available RAM, and `--cpu-offload-gb` pins host memory that cannot swap. No
   placement of this checkpoint fits on this box, so a from-scratch reference run is out.

What remains is what other people already published. This tool is the ingestion path for that:
**nothing is trusted because it is on the Hub.** Every artefact is fetched at a pinned dataset
revision, hashed against the publisher's own manifest, and reported next to what the publisher
does *not* state (model revision, tokeniser identity, engine). A trace is a reference only when
those gaps are known and written down.

Four datasets, and what each is for:

| dataset | size | what it actually is |
|---|---|---|
| `Vemloir/Qwen3.8-Flash-Next-traces` | 0.38 GiB | calibration **inputs** only (`input_ids` + `lengths`), generated by the model itself |
| `satsder/qwen3.8-flash-next-routing-traces` | 45.85 GiB (one `.7z`, not fetched) | llama.cpp-branch hidden/router/expert dumps, 85 request directories |
| `jyohukuchan/qwen38-flash-next-bf16-logits` | 78.82 GiB (21 cases) | **BF16 reference logits**, exllamav3, Wikitext-2 + mtp-bench, FP32 rows |
| `aswinkumar99/qwen3.8-flash-next-expert-traces` | 1046 GiB | FreeToken traces: per-token/per-layer top-10 experts, top-32 router logits, 5-tap states, LM-head top-8 |

Modes
-----

    inspect   fetch each dataset's small metadata, print what it provides and what it does not,
              write traces/published/provenance.json
    verify    sha256 every downloaded artefact against the publisher's manifest
    kl        reproduce the publisher's per-case KL(reference || candidate) in float64
    router    compare aswinkumar99's router/HC weights with the local checkpoint, bit for bit
    router-trace  recompute the recorded router logits from the recorded taps and our gate weights
    to-trace  write one logits case as a safetensors trace in `reference_trace.py`'s shape
              (`p0/prompt_ids`, `p0/prompt_logits`, provenance metadata), so the KL/PPL helpers in
              `reference_trace.py` apply to a published reference unchanged

Examples
--------

    PY=./.venv/bin/python
    $PY published_traces.py inspect
    $PY published_traces.py verify
    $PY published_traces.py kl --case wiki2_r0
    $PY published_traces.py router --model ~/models/qwen38-flash-next-nvfp4
    $PY published_traces.py to-trace --case en_prose_129 --out traces/published/en_prose_129.safetensors

Everything downloaded here lives under `traces/` (gitignored). The only committed artefacts of
this lane are this file and the note in REAL_REFERENCE.md.
"""

