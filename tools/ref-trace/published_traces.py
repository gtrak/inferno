def cmd_inspect(arguments) -> int:
    PUBLISHED.mkdir(parents=True, exist_ok=True)
    for dataset, files in METADATA.items():
        for path, budget in files.items():
            if budget:
                fetch(dataset, path, budget)
    report = {
        "note": (
            "Published traces are references only as far as their provenance goes. Each block below lists "
            "what was measured from the files and what the publisher does not state."
        ),
        "datasets": {
            "vemloir": {"dataset": DATASETS["vemloir"], **inspect_vemloir()},
            "routing": {"dataset": DATASETS["routing"], **inspect_routing()},
            "logits": {"dataset": DATASETS["logits"], **inspect_logits()},
            "expert": {"dataset": DATASETS["expert"], **inspect_expert()},
        },
    }
    out = PUBLISHED / "provenance.json"
    out.write_text(json.dumps(report, indent=2) + "\n")
    print(f"wrote {out}")
    for name, block in report["datasets"].items():
        print(f"\n{name}: {block['dataset']['repo']} @ {block['dataset']['revision'][:12]}")
        print(f"  provides: {block['provides']}")
        print(f"  does not: {block['does_not_provide']}")
    return 0


