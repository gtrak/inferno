def cmd_verify(arguments) -> int:
    failures = 0
    checked = 0
    # logits: manifest.json lists sha256 + bytes for every file in the dataset.
    root = PUBLISHED / "logits"
    if (root / "manifest.json").exists():
        manifest = load_json(root / "manifest.json")
        for entry in manifest["files"]:
            path = root / entry["path"]
            if not path.exists():
                continue
            checked += 1
            ok = path.stat().st_size == entry["bytes"] and sha256_file(path) == entry["sha256"]
            failures += 0 if ok else 1
            print(f"  {'OK  ' if ok else 'FAIL'} logits/{entry['path']}")
    # expert: the per-part manifest names dtype/shape/bytes/sha256 for every array.
    root = PUBLISHED / "expert"
    if (root / "compact/batch-001/manifest.json").exists():
        arrays = load_json(root / "compact/batch-001/manifest.json")["arrays"]
        for name, spec in arrays.items():
            path = root / "compact/batch-001" / name
            if not path.exists():
                continue
            checked += 1
            ok = path.stat().st_size == spec["bytes"] and sha256_file(path) == spec["sha256"]
            failures += 0 if ok else 1
            print(f"  {'OK  ' if ok else 'FAIL'} expert/compact/batch-001/{name}")
    # vemloir publishes no per-file sha256: the revision plus the recorded size is all there is.
    for part in ("agents", "chat", "multimodal"):
        path = PUBLISHED / "vemloir" / part / "cal_trace.safetensors"
        if path.exists():
            checked += 1
            print(f"  ..  vemloir/{part}/cal_trace.safetensors {path.stat().st_size} bytes "
                  "(no published sha256; revision-pinned, size recorded)")
    print(f"\nverified {checked} file(s), {failures} failure(s)")
    return 1 if failures else 0


