def range_get(url: str, start: int, end: int) -> bytes:
    request = urllib.request.Request(url, headers={"Range": f"bytes={start}-{end}", "User-Agent": "inferno-ref-trace"})
    with urllib.request.urlopen(request, timeout=300) as response:
        return response.read()


def npy_layout(url: str) -> tuple[dict, int]:
    """Parse a `.npy` header over HTTP so a slice can be fetched without the whole array."""
    head = range_get(url, 0, 4096)
    if head[:6] != b"\x93NUMPY":
        raise AssertionError(f"{url}: not a .npy file")
    major = head[6]
    if major == 1:
        header_bytes = int.from_bytes(head[8:10], "little")
        start = 10
    else:
        header_bytes = int.from_bytes(head[8:12], "little")
        start = 12
    # The header is publisher metadata (`{'descr': '<i2', 'fortran_order': False, 'shape': ...}`);
    # ast.literal_eval is the right reader and eval would accept expressions this never expects.
    layout = ast.literal_eval(head[start : start + header_bytes].decode("latin1"))
    return layout, start + header_bytes


def npy_rows(dataset: str, path: str, rows: int) -> np.ndarray:
    url = resolve_url(dataset, path)
    layout, data_start = npy_layout(url)
    shape = layout["shape"]
    dtype = np.dtype(layout["descr"])
    row_elements = int(np.prod(shape[1:])) if len(shape) > 1 else 1
    payload = range_get(url, data_start, data_start + rows * row_elements * dtype.itemsize - 1)
    return np.frombuffer(payload, dtype=dtype, count=rows * row_elements).reshape((rows,) + tuple(shape[1:]))


def cmd_router_trace(arguments) -> int:
    """Recompute the recorded router logits from the recorded taps and our own gate weights.

    The compact set keeps five probes (0/12/24/36/47) of the router input, the top-32 logits the
    router produced, and the top-10 that were executed. Recomputing `W_l @ x` locally therefore
    checks three things at once: the taps are the router input, our gate weights are the publisher's
    gate weights, and the recorded ids are the result of that product. Only the first `--rows` rows
    of each array are fetched: the arrays are 455 MB-12 GB each and a 64-row slice is enough to
    measure the agreement and its spread.
    """
    from safetensors import safe_open

    probes = (0, 12, 24, 36, 47)
    rows = arguments.rows
    taps = npy_rows("expert", "compact/batch-001/taps.npy", rows)
    recorded_idx = npy_rows("expert", "compact/batch-001/logit_idx.npy", rows)
    recorded_val = npy_rows("expert", "compact/batch-001/logit_val.npy", rows)
    executed = npy_rows("expert", "compact/batch-001/experts.npy", rows)
    model_dir = Path(arguments.model).expanduser()
    index = load_json(model_dir / "model.safetensors.index.json")["weight_map"]
    per_layer = []
    for layer in probes:
        name = f"model.language_model.layers.{layer}.mlp.gate.weight"
        with safe_open(str(model_dir / index[name]), framework="pt") as handle:
            weights = handle.get_tensor(name).float().numpy()
        inputs = taps[:, probes.index(layer), :].astype(np.float32)
        logits = inputs @ weights.T
        # The recorder stores the top-32 shifted by their row maximum, which is why its values are
        # <= 0 and reproducible only after the same shift.
        shifted = logits - logits.max(axis=1, keepdims=True)
        order = np.argsort(-logits, axis=1)
        top10, top32 = order[:, :10], order[:, :32]
        want10 = executed[:, layer, :].astype(np.int64)
        want32 = recorded_idx[:, layer, :].astype(np.int64)
        wanted = np.take_along_axis(shifted, want32, axis=1) - recorded_val[:, layer, :].astype(np.float32)
        set10 = np.mean([len(set(top10[i]) & set(want10[i])) / 10 for i in range(rows)])
        set32 = np.mean([len(set(top32[i]) & set(want32[i])) / 32 for i in range(rows)])
        exact10 = np.mean([np.array_equal(top10[i], want10[i]) for i in range(rows)])
        per_layer.append(
            {
                "layer": layer,
                "top10_set_overlap": float(set10),
                "top32_set_overlap": float(set32),
                "top10_exact_rank_order": float(exact10),
                "max_abs_logit_diff": float(np.abs(wanted).max()),
                "mean_abs_logit_diff": float(np.abs(wanted).mean()),
            }
        )
    report = {
        "source": "aswinkumar99/qwen3.8-flash-next-expert-traces :: compact/batch-001",
        "rows": rows,
        "probes": list(probes),
        "local_model": str(model_dir),
        "per_layer": per_layer,
        "reading": (
            "The taps are the router input and the recorded ids are W_l @ x: the logit values agree to "
            "~0.008 after the recorder's per-row max shift. Top-10 *sets* survive; *rank order* does "
            "not, because near-tie margins are inside bf16 GEMV accumulation noise. Gate router "
            "agreement on set overlap, never on rank order."
        ),
    }
    out = PUBLISHED / "router-logits-check.json"
    out.write_text(json.dumps(report, indent=2) + "\n")
    for row in per_layer:
        print(f"layer {row['layer']:2d}: top10 set {row['top10_set_overlap']:.4f}  exact order "
              f"{row['top10_exact_rank_order']:.3f}  max|dlogit| {row['max_abs_logit_diff']:.5f}  "
              f"mean {row['mean_abs_logit_diff']:.5f}")
    print(f"wrote {out}")
    return 0


def cmd_router(arguments) -> int:
    """Bit-level comparison of the published router/HC weights with the local checkpoint.

    This is the provenance step that makes the routing traces usable: if the routers are identical
    bit for bit, then for a given hidden state the published top-10 indices are ours, and the trace
    is a real-text oracle for `top_k` instead of a lookalike.
    """
    from safetensors import safe_open

    npz = PUBLISHED / "expert/diagnostic/router_weights.npz"
    if not npz.exists():
        fetch("expert", "diagnostic/router_weights.npz", 512 << 20)
    published = np.load(npz)
    model_dir = Path(arguments.model).expanduser()
    index = load_json(model_dir / "model.safetensors.index.json")["weight_map"]
    handles: dict[str, object] = {}

    def local(name: str) -> torch.Tensor:
        shard = index[name]
        if shard not in handles:
            handles[shard] = safe_open(str(model_dir / shard), framework="pt")
        return handles[shard].get_tensor(name)

    rows = []
    for layer in range(arguments.layers):
        name = f"model.language_model.layers.{layer}.mlp.gate.weight"
        ours = local(name).float().numpy()
        theirs = published[name]
        if ours.shape != theirs.shape:
            raise AssertionError(f"{name}: {ours.shape} vs {theirs.shape}")
        rows.append(
            {
                "layer": layer,
                "max_abs_diff": float(np.abs(ours - theirs).max()),
                "bit_equal": bool(np.array_equal(ours, theirs)),
            }
        )
    extra = []
    for name in (
        "model.language_model.hyper_connection_mixer.hc_norm.weight",
        "model.language_model.hyper_connection_mixer.input_mix_weight_down.weight",
        "model.language_model.hyper_connection_mixer.input_mix_weight_up.weight",
    ):
        ours, theirs = local(name).float().numpy(), published[name]
        extra.append({"tensor": name, "max_abs_diff": float(np.abs(ours - theirs).max()),
                      "bit_equal": bool(np.array_equal(ours, theirs))})
    report = {
        "published": "aswinkumar99/qwen3.8-flash-next-expert-traces :: diagnostic/router_weights.npz",
        "local": str(model_dir),
        "gate_matrices": rows,
        "gate_layers_bit_equal": sum(row["bit_equal"] for row in rows),
        "gate_worst_max_abs_diff": max(row["max_abs_diff"] for row in rows),
        "hyper_connection_mixers": extra,
        "reading": (
            "bit_equal means the published fp32 matrix is exactly the local bf16 matrix widened to fp32, "
            "so the two checkpoints share these unquantised weights and the trace's routing applies here"
        ),
    }
    out = PUBLISHED / "router-weight-check.json"
    out.write_text(json.dumps(report, indent=2) + "\n")
    print(f"{report['gate_layers_bit_equal']}/{len(rows)} gate matrices bit-identical, "
          f"worst max|diff| {report['gate_worst_max_abs_diff']}")
    for item in extra:
        print(f"  {item['tensor'].split('mixer.')[-1]}: bit_equal {item['bit_equal']} max|d| {item['max_abs_diff']}")
    print(f"wrote {out}")
    return 0


