def dataset_file(dataset: str, path: str) -> Path:
    return PUBLISHED / dataset / path


def resolve_url(dataset: str, path: str) -> str:
    entry = DATASETS[dataset]
    return f"https://huggingface.co/{entry['kind']}s/{entry['repo']}/resolve/{entry['revision']}/{path}"


def fetch(dataset: str, path: str, budget: int, force: bool = False) -> Path:
    """Download one file at the pinned revision. `budget == 0` means "only if asked explicitly"."""
    target = dataset_file(dataset, path)
    if target.exists() and not force:
        return target
    if budget == 0:
        raise AssertionError(f"{dataset}:{path} is not part of the small-metadata set; fetch it explicitly")
    target.parent.mkdir(parents=True, exist_ok=True)
    request = urllib.request.Request(resolve_url(dataset, path), headers={"User-Agent": "inferno-ref-trace"})
    with urllib.request.urlopen(request, timeout=300) as response:
        declared = int(response.headers.get("Content-Length", "0"))
        if declared and declared > budget:
            raise AssertionError(f"{dataset}:{path} is {declared} bytes, over the {budget}-byte budget")
        payload = response.read()
    target.write_bytes(payload)
    print(f"  fetched {dataset}/{path} {len(payload)} bytes")
    return target


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def load_json(path: Path):
    return json.loads(path.read_text())


