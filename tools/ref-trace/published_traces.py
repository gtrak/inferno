def cmd_to_trace(arguments) -> int:
    """Write `p0/prompt_ids` + `p0/prompt_logits` and the provenance that produced them.

    The key layout is `reference_trace.py`'s, so `reference_trace.distribution_metrics` (KL in
    float64, top-1 agreement, ΔPPL) runs on a published reference exactly as it runs on a generated
    one. There is no `gen_logits`: the published cases are single teacher-forced passes.
    """
    from safetensors.torch import save_file

    root = PUBLISHED / "logits"
    logits, case = load_case(root, arguments.case, "reference")
    inputs = {item["id"]: item for item in load_json(root / "corpus/all-cases.json")["cases"]}
    if arguments.case not in inputs:
        raise AssertionError(f"{arguments.case}: no published input ids")
    token_ids = inputs[arguments.case]["token_ids"]
    if len(token_ids) != case["shape"][0]:
        raise AssertionError(f"{arguments.case}: {len(token_ids)} ids for {case['shape'][0]} logits rows")
    tensors = {
        "p0/prompt_ids": torch.tensor(token_ids, dtype=torch.int64),
        "p0/prompt_logits": torch.from_numpy(np.array(logits)).to(torch.float32).contiguous(),
    }
    metadata = {
        "mode": "published",
        "dataset": "jyohukuchan/qwen38-flash-next-bf16-logits",
        "dataset_revision": DATASETS["logits"]["revision"],
        "case": arguments.case,
        "model": "Qwen/Qwen3.8-Flash-Next",
        "model_revision": "de4b8e4d43b917e7706784d8bb445c9af86a3540",
        "engine": "exllamav3 (BF16 weights)",
        "dtype": "output of a bf16 model, stored float32",
        "positions": str(case["shape"][0]),
        "input_token_ids_sha256": str(case.get("input_token_ids_sha256")),
        "nonfinite_count": str(case.get("nonfinite_count")),
        "note": (
            "published reference, not generated here; no generated positions, no noise floor of our own. "
            "Every gate that uses it must sit above the publisher's cross-engine disagreement "
            "(results/engine-crosscheck.json)."
        ),
    }
    out = Path(arguments.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    save_file(tensors, str(out), metadata=metadata)
    print(f"wrote {out}: {sum(t.numel() for t in tensors.values())} elements")
    return 0


