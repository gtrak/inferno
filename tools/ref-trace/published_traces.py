def load_case(root: Path, case_id: str, kind: str) -> tuple[np.ndarray, dict]:
    manifest = load_json(root / kind / "manifest.json")
    case = next(entry for entry in manifest["cases"] if entry["id"] == case_id)
    shape = tuple(case["shape"])
    path = root / kind / case["logits_file"]
    expected = shape[0] * shape[1] * 4
    if not path.exists():
        # One case at a time: the dataset is 78.8 GiB and a reference run needs one case, not all 21.
        print(f"  fetching {kind}/{case['logits_file']} ({expected} bytes, case {case_id})")
        fetch("logits", f"{kind}/{case['logits_file']}", expected)
    if path.stat().st_size != expected:
        raise AssertionError(f"{path}: {path.stat().st_size} bytes, manifest says {shape}")
    if case.get("nonfinite_count"):
        raise AssertionError(f"{case_id}: manifest reports {case['nonfinite_count']} non-finite logits")
    return np.memmap(path, dtype="<f4", mode="r", shape=shape), case


def cmd_kl(arguments) -> int:
    """KL(reference || candidate) over the scored rows, exactly as the publisher defines it.

    The three sides of the comparison are aligned by *position*, not by row: the reference keeps the
    55-token chat-template prefix for WikiText-2 rows and the turboderp candidate drops it, so the
    start offset is `--start` (default 55 for `wiki2_*`, 0 otherwise).
    """
    root = PUBLISHED / "logits"
    reference, ref_case = load_case(root, arguments.case, "reference")
    candidate, cand_case = load_case(root, arguments.case, arguments.candidate)
    if ref_case["shape"] != cand_case["shape"]:
        raise AssertionError(f"shape mismatch {ref_case['shape']} vs {cand_case['shape']}")
    total_rows = int(ref_case["shape"][0])
    start = arguments.start if arguments.start is not None else (55 if arguments.case.startswith("wiki2_") else 0)
    if not 0 <= start < total_rows:
        raise AssertionError(f"{arguments.case}: --start {start} is outside 0..{total_rows}")
    raw_vocab_size = int(ref_case["shape"][1])
    # The publisher scores the 248,077 valid ids, not the 248,320 padded rows (see compare.py):
    # the 243 padding rows hold no distribution and would otherwise take part in the normalisation.
    valid_ids = torch.tensor(load_json(root / "vocab.json")["valid_token_ids"], dtype=torch.long)

    kls, top1 = [], []
    for begin in range(start, total_rows, arguments.block_rows):
        end = min(begin + arguments.block_rows, total_rows)
        a = torch.from_numpy(np.array(reference[begin:end], dtype=np.float32)).double().index_select(1, valid_ids)
        b = torch.from_numpy(np.array(candidate[begin:end], dtype=np.float32)).double().index_select(1, valid_ids)
        log_p = torch.log_softmax(a, dim=-1)
        log_q = torch.log_softmax(b, dim=-1)
        kls.append((log_p.exp() * (log_p - log_q)).sum(-1))
        top1.append(a.argmax(-1) == b.argmax(-1))
    kl = torch.cat(kls).double()
    agreement = torch.cat(top1).double()
    measured = {
        "case": arguments.case,
        "candidate": arguments.candidate,
        "rows_scored": int(total_rows - start),
        "rows_dropped_as_prefix": int(start),
        "vocab_size_scored": int(valid_ids.numel()),
        "vocab_size_padded": raw_vocab_size,
        "kl_mean": float(kl.mean()),
        "kl_p50": float(torch.quantile(kl, 0.5)),
        "kl_p99": float(torch.quantile(kl, 0.99)),
        "kl_max": float(kl.max()),
        "top1_agreement": float(agreement.mean()),
        "definition": "KL(softmax(reference) || softmax(candidate)), temperature 1, nats, float64",
        "reference": "jyohukuchan/reference (BF16, exllamav3)",
        "reference_model_revision": "de4b8e4d43b917e7706784d8bb445c9af86a3540",
    }
    published = None
    if "turboderp" in arguments.candidate:
        results = root / "results" / "kl-wiki2-td.json"
    elif arguments.case.startswith("wiki2_"):
        results = root / "results" / "kl-wiki2-xe.json"
    else:
        results = root / "results" / "kl-xestrata-vs-bf16.json"
    if results.exists():
        document = load_json(results)
        for case in document.get("cases", []):
            if case["id"] == arguments.case:
                published = {"kl_mean": case["kld"]["mean"], "top1_agreement": case["top1_agreement"]}
    if published:
        measured["published"] = published
        measured["reproduces_published"] = (
            abs(published["kl_mean"] - measured["kl_mean"]) < 1e-9
            and abs(published["top1_agreement"] - measured["top1_agreement"]) < 1e-9
        )
        measured["abs_diff_vs_published"] = {
            "kl_mean": abs(published["kl_mean"] - measured["kl_mean"]),
            "top1_agreement": abs(published["top1_agreement"] - measured["top1_agreement"]),
        }
    out = PUBLISHED / "kl" / f"{arguments.case}.{arguments.candidate}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(measured, indent=2) + "\n")
    print(json.dumps(measured, indent=2))
    print(f"wrote {out}")
    return 0


